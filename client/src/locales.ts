export function isLanguage(value: unknown): value is Language {
  return typeof value === "string" && SUPPORTED_LANGUAGES.includes(value as Language);
}

export function detectLanguage(): Language {
  if (typeof window === "undefined") return "de";
  const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  if (isLanguage(stored)) return stored;
  const candidates = navigator.languages?.length ? navigator.languages : [navigator.language];
  return candidates.some((candidate) => candidate.toLowerCase().startsWith("en")) ? "en" : "de";
}

export function localeFor(language: Language): string {
  return language === "en" ? "en-GB" : "de-DE";
}

export function translate(language: Language, key: string, values: TranslationValues = {}): string {
  const template = language === "en" ? english[key] ?? key : key;
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : match,
  );
}

export function translateServerMessage(language: Language, message: string): string {
  if (language === "de") return message;
  const translated = english[message];
  if (translated) return translated;
  const requestFailed = message.match(/^Anfrage fehlgeschlagen \((\d+)\)\.$/);
  if (requestFailed) return `Request failed (${requestFailed[1]}).`;
  const spotifyError = message.match(/^Spotify-Fehler \((\d+)\)\.$/);
  if (spotifyError) return `Spotify error (${spotifyError[1]}).`;
  const waitSeparator = " Verbleibende Wartezeit: ca. ";
  const separatorIndex = message.indexOf(waitSeparator);
  if (separatorIndex >= 0) {
    const introduction = message.slice(0, separatorIndex);
    const wait = message.slice(separatorIndex + waitSeparator.length)
      .replace(/(\d+) Std\./g, "$1 hr")
      .replace(/(\d+) Min\./g, "$1 min")
      .replace(/(\d+) Sek\./g, "$1 sec");
    return `${english[introduction] ?? introduction} Remaining wait: about ${wait}`;
  }
  return message;
}
